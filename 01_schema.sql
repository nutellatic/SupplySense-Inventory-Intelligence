-- SupplySense v2 | Oracle Database Free 23ai/26ai (12c+ identity syntax)
-- Run while connected as the dedicated SUPPLYSENSE schema user.
SET DEFINE OFF

CREATE TABLE suppliers (
  supplier_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  supplier_name VARCHAR2(100) NOT NULL,
  email VARCHAR2(150) NOT NULL UNIQUE,
  phone VARCHAR2(25),
  address VARCHAR2(250),
  lead_time_days NUMBER(3) DEFAULT 7 NOT NULL CHECK (lead_time_days BETWEEN 1 AND 120)
);

CREATE TABLE categories (
  category_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category_name VARCHAR2(80) NOT NULL UNIQUE,
  description VARCHAR2(250)
);

CREATE TABLE products (
  product_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  supplier_id NUMBER NOT NULL REFERENCES suppliers(supplier_id),
  category_id NUMBER NOT NULL REFERENCES categories(category_id),
  product_name VARCHAR2(120) NOT NULL,
  sku VARCHAR2(40) NOT NULL UNIQUE,
  unit_price NUMBER(10,2) NOT NULL CHECK (unit_price >= 0),
  unit_cost NUMBER(10,2) DEFAULT 0 NOT NULL CHECK (unit_cost >= 0),
  quantity_in_stock NUMBER(10) DEFAULT 0 NOT NULL CHECK (quantity_in_stock >= 0),
  reorder_level NUMBER(10) DEFAULT 10 NOT NULL CHECK (reorder_level >= 0),
  created_at DATE DEFAULT SYSDATE NOT NULL,
  CONSTRAINT ck_products_price_cost CHECK (unit_price >= unit_cost)
);

CREATE TABLE customers (
  customer_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_name VARCHAR2(100) NOT NULL,
  email VARCHAR2(150) NOT NULL UNIQUE,
  phone VARCHAR2(25)
);

CREATE TABLE purchase_orders (
  purchase_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  purchase_reference VARCHAR2(30) NOT NULL UNIQUE,
  supplier_id NUMBER NOT NULL REFERENCES suppliers(supplier_id),
  order_date DATE DEFAULT SYSDATE NOT NULL,
  status VARCHAR2(12) DEFAULT 'PENDING' NOT NULL,
  CONSTRAINT ck_purchase_status CHECK (status IN ('PENDING','RECEIVED','CANCELLED'))
);

CREATE TABLE purchase_items (
  purchase_item_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  purchase_id NUMBER NOT NULL REFERENCES purchase_orders(purchase_id),
  product_id NUMBER NOT NULL REFERENCES products(product_id),
  quantity NUMBER(10) NOT NULL CHECK (quantity > 0),
  unit_cost NUMBER(10,2) NOT NULL CHECK (unit_cost >= 0),
  CONSTRAINT uq_purchase_product UNIQUE (purchase_id, product_id)
);

CREATE TABLE sales (
  sale_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sale_reference VARCHAR2(30) NOT NULL UNIQUE,
  customer_id NUMBER NOT NULL REFERENCES customers(customer_id),
  sale_date DATE DEFAULT SYSDATE NOT NULL,
  total_amount NUMBER(12,2) DEFAULT 0 NOT NULL CHECK (total_amount >= 0)
);

CREATE TABLE sale_items (
  sale_item_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sale_id NUMBER NOT NULL REFERENCES sales(sale_id),
  product_id NUMBER NOT NULL REFERENCES products(product_id),
  quantity NUMBER(10) NOT NULL CHECK (quantity > 0),
  unit_price NUMBER(10,2) NOT NULL CHECK (unit_price >= 0),
  CONSTRAINT uq_sale_product UNIQUE (sale_id, product_id)
);

CREATE TABLE inventory_audit (
  audit_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id NUMBER NOT NULL REFERENCES products(product_id),
  old_quantity NUMBER(10) NOT NULL,
  new_quantity NUMBER(10) NOT NULL,
  quantity_delta NUMBER(10) NOT NULL,
  changed_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  change_note VARCHAR2(250) DEFAULT 'Stock quantity changed' NOT NULL
);

CREATE INDEX idx_products_name ON products(product_name);
CREATE INDEX idx_products_stock ON products(quantity_in_stock, reorder_level);
CREATE INDEX idx_sales_date ON sales(sale_date);
CREATE INDEX idx_sale_items_product ON sale_items(product_id);
CREATE INDEX idx_purchase_items_product ON purchase_items(product_id);
CREATE INDEX idx_audit_product_date ON inventory_audit(product_id, changed_at);

PROMPT SupplySense tables and indexes created.
